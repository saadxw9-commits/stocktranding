#!/usr/bin/env python3
"""يجهّز المهارات المسجّلة في config/skills-registry.yaml داخل .claude/skills/.

- على لينكس وماك: روابط رمزية، فيظهر أي تحديث في vendor/ فورًا.
- على ويندوز (أو عند تعذّر الروابط): نسخ حقيقية. أعد تشغيل السكربت بعد كل تحديث للمستودعات الخارجية.
- يمكن فرض النسخ بالمتغير LINK_MODE=copy.

المجلد .claude/skills مولَّد وغير مرفوع إلى git، فلا تعدّل ما بداخله يدويًا.
"""
from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / ".claude" / "skills"
SKIP_GROUPS = {"crypto_reserved"}
MARKER = ".generated-copy"   # يميّز النسخ المولَّدة عن أي مجلد وضعته أنت


def wanted_skills() -> dict[str, Path]:
    reg = yaml.safe_load((ROOT / "config" / "skills-registry.yaml").read_text(encoding="utf-8"))
    wanted: dict[str, Path] = {}
    for group, names in reg.get("tradermonty", {}).items():
        if group in SKIP_GROUPS:
            continue
        for n in names:
            wanted[n] = ROOT / "vendor" / "tradermonty" / "skills" / n
    for plugin, names in reg.get("anthropic_fs", {}).items():
        for n in names:
            wanted[n] = ROOT / "vendor" / "anthropic-fs" / "plugins" / "vertical-plugins" / plugin / "skills" / n
    for n in reg.get("ours", []):
        wanted[n] = ROOT / "skills" / n
    return wanted


def remove(p: Path) -> None:
    """يحذف رابطًا أو نسخة مولَّدة أو ملفًّا نصيًّا بديلًا للرابط (ما يكتبه git على ويندوز)."""
    if p.is_symlink() or p.is_file():
        p.unlink()
    elif p.is_dir():
        if (p / MARKER).exists():
            shutil.rmtree(p)
        else:
            raise SystemExit(f"المجلد {p} ليس مولَّدًا؛ لن أحذفه. انقله أو احذفه بنفسك ثم أعد التشغيل.")


def main() -> int:
    wanted = wanted_skills()
    missing = [n for n, p in wanted.items() if not (p / "SKILL.md").exists()]
    for n in missing:
        print(f"مفقودة: {n}  ({wanted[n]})  — هل جهّزت الوحدات الفرعية؟ git submodule update --init", file=sys.stderr)

    TARGET.mkdir(parents=True, exist_ok=True)
    mode = "copy" if os.environ.get("LINK_MODE") == "copy" or os.name == "nt" else "symlink"

    # أزل ما لم يعد مسجّلًا
    for entry in TARGET.iterdir():
        if entry.name not in wanted:
            remove(entry)
            print(f"أُزيل: {entry.name}")

    linked = copied = 0
    for n, src in wanted.items():
        if n in missing:
            continue
        dst = TARGET / n
        if dst.exists() or dst.is_symlink():
            remove(dst)
        if mode == "symlink":
            try:
                dst.symlink_to(os.path.relpath(src, TARGET), target_is_directory=True)
                linked += 1
                continue
            except OSError:
                mode = "copy"
                print("تعذّرت الروابط الرمزية؛ سأستخدم النسخ.")
        shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        (dst / MARKER).write_text("generated by scripts/link_skills.py\n", encoding="utf-8")
        copied += 1

    print(f"الوضع: {mode} — روابط {linked}، نسخ {copied}، مفقود {len(missing)}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
